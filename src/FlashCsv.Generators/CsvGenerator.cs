    private static (object? Min, object? Max) GetNumericBounds(IPropertySymbol property)
    {
        object? min = null;
        object? max = null;
        foreach (var attr in property.GetAttributes())
        {
            string? name = attr.AttributeClass?.Name;
            if (name is "CsvRangeAttribute" or "CsvRange" && attr.ConstructorArguments.Length >= 2)
            {
                min = attr.ConstructorArguments[0].Value;
                max = attr.ConstructorArguments[1].Value;
            }
            else if (name is "CsvMinAttribute" or "CsvMin" && attr.ConstructorArguments.Length >= 1) min = attr.ConstructorArguments[0].Value;
            else if (name is "CsvMaxAttribute" or "CsvMax" && attr.ConstructorArguments.Length >= 1) max = attr.ConstructorArguments[0].Value;
        }
        return (min, max);
    }

    private static (int? Min, int? Max) GetLengthBounds(IPropertySymbol property)
    {
        int? min = null;
        int? max = null;
        foreach (var attr in property.GetAttributes())
        {
            string? name = attr.AttributeClass?.Name;
            if (name is "CsvLengthAttribute" or "CsvLength" && attr.ConstructorArguments.Length >= 2)
            {
                if (attr.ConstructorArguments[0].Value is int minVal) min = minVal;
                if (attr.ConstructorArguments[1].Value is int maxVal) max = maxVal;
