    private static (bool IsFlattened, string Prefix) GetFlattenInfo(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvFlattenAttribute" or "CsvFlatten")
            {
                string prefix = string.Empty;
                if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string ctorPrefix)
                {
                    prefix = ctorPrefix;
                }
                else
                {
                    var prefixNamed = attr.NamedArguments.FirstOrDefault(kvp => kvp.Key == "Prefix");
                    if (prefixNamed.Value.Value is string namedPrefix) prefix = namedPrefix;
                }
                return (true, prefix);
            }
        }
        return (false, string.Empty);
    }

    private static (string PrimaryName, List<string> Aliases) GetPropertyAliases(IPropertySymbol prop, string prefix = "")
    {
        var rawAliases = new List<string>();
        foreach (var attr in prop.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvNameAttribute" or "CsvName")
            {
                foreach (var arg in attr.ConstructorArguments)
                {
                    if (arg.Values.Length > 0)
                    {
                        foreach (var val in arg.Values)
                        {
                            if (val.Value is string nameStr && !string.IsNullOrEmpty(nameStr)) rawAliases.Add(prefix + nameStr);
                        }
                    }
                    else if (arg.Value is string directStr && !string.IsNullOrEmpty(directStr)) rawAliases.Add(prefix + directStr);
                }
            }
        }

        if (rawAliases.Count == 0)
        {
            string baseName = prop.Name;
            rawAliases.Add(prefix + baseName);
            rawAliases.Add(prefix + ToSnakeCase(baseName));
            rawAliases.Add(prefix + ToKebabCase(baseName));
            rawAliases.Add(prefix + ToCamelCase(baseName));
        }
        else
        {
            rawAliases.Add(prefix + prop.Name);
        }

        string primaryName = rawAliases[0];
        var distinctAliases = rawAliases.Distinct().ToList();
        return (primaryName, distinctAliases);
    }

