    }

    private static (string[] TrueValues, string[] FalseValues)? GetBooleanCustomValues(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvBooleanAttribute" or "CsvBoolean")
            {
                if (attr.ConstructorArguments.Length == 1)
                {
                    var trueArg = attr.ConstructorArguments[0];
                    string[] trueVals = trueArg.Values.Select(v => v.Value?.ToString() ?? "").Where(s => !string.IsNullOrEmpty(s)).ToArray();
                    return (trueVals, Array.Empty<string>());
                }
                else if (attr.ConstructorArguments.Length >= 2)
                {
                    var trueArg = attr.ConstructorArguments[0];
                    var falseArg = attr.ConstructorArguments[1];
                    string[] trueVals = trueArg.Values.Select(v => v.Value?.ToString() ?? "").Where(s => !string.IsNullOrEmpty(s)).ToArray();
                    string[] falseVals = falseArg.Values.Select(v => v.Value?.ToString() ?? "").Where(s => !string.IsNullOrEmpty(s)).ToArray();
                    return (trueVals, falseVals);
                }
            }
        }
        return null;
    }

