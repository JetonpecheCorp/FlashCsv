            else if (name is "CsvMaxLengthAttribute" or "CsvMaxLength" && attr.ConstructorArguments.Length >= 1)
            {
                if (attr.ConstructorArguments[0].Value is int maxVal) max = maxVal;
            }
        }
        return (min, max);
    }

