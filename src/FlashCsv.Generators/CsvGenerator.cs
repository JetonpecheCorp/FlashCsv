    private static (char Delimiter, char EscapeChar)? GetDelimiterArrayInfo(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvDelimiterArrayAttribute" or "CsvDelimiterArray")
            {
                char delimiter = ';';
                char escapeChar = '\0';
                if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is char d) delimiter = d;
                if (attr.ConstructorArguments.Length > 1 && attr.ConstructorArguments[1].Value is char e) escapeChar = e;
                return (delimiter, escapeChar);
            }
        }
        return null;
    }

    private static List<(IPropertySymbol Property, string Prefix, IPropertySymbol? ParentProp)> GetAllFlattenedProperties(List<IPropertySymbol> properties)
    {
        var result = new List<(IPropertySymbol Property, string Prefix, IPropertySymbol? ParentProp)>();
        foreach (var prop in properties)
        {
            var (isFlattened, prefix) = GetFlattenInfo(prop);
            if (isFlattened && prop.Type is INamedTypeSymbol childType)
            {
                var childProps = GetMappableProperties(childType);
                foreach (var child in childProps) result.Add((child, prefix, prop));
            }
            else
            {
                result.Add((prop, string.Empty, null));
            }
        }
        return result;
    }

    private static bool HasRequiredAttribute(IPropertySymbol property) => property.GetAttributes().Any(a => a.AttributeClass?.Name is "CsvRequiredAttribute" or "CsvRequired");
    private static bool HasIgnoreAttribute(IPropertySymbol property) => property.GetAttributes().Any(a => a.AttributeClass?.Name is "CsvIgnoreAttribute" or "CsvIgnore");
    private static bool HasSanitizeFormulaAttribute(IPropertySymbol property) => property.GetAttributes().Any(a => a.AttributeClass?.Name is "CsvSanitizeFormulaAttribute" or "CsvSanitizeFormula");

    private static bool HasPropertyInitializer(IPropertySymbol property)
    {
        foreach (var syntaxRef in property.DeclaringSyntaxReferences)
        {
            var syntax = syntaxRef.GetSyntax();
            if (syntax is PropertyDeclarationSyntax propDecl && propDecl.Initializer != null) return true;
        }
        return false;
    }

    private static bool IsEnumType(ITypeSymbol type, out INamedTypeSymbol enumType)
    {
        var unwrapped = UnwrapNullable(type);
        if (unwrapped.TypeKind == TypeKind.Enum && unwrapped is INamedTypeSymbol named)
        {
            enumType = named;
            return true;
        }
        enumType = null!;
        return false;
    }

    private static bool IsArrayOrList(ITypeSymbol type, out ITypeSymbol elementType, out bool isList)
    {
        if (type is IArrayTypeSymbol arrayType)
        {
            elementType = arrayType.ElementType;
            isList = false;
            return true;
        }
        if (type is INamedTypeSymbol named && named.IsGenericType)
        {
            string genericName = named.ConstructedFrom.ToDisplayString();
            if (genericName is "System.Collections.Generic.List<T>" or "System.Collections.Generic.IList<T>" or "System.Collections.Generic.IReadOnlyList<T>")
            {
                elementType = named.TypeArguments[0];
                isList = true;
                return true;
            }
        }
        elementType = null!;
        isList = false;
        return false;
    }

    private static bool IsRowNumber(IPropertySymbol property) => property.GetAttributes().Any(a => a.AttributeClass?.Name is "CsvRowNumberAttribute" or "CsvRowNumber");
    private static bool IsExtensionData(IPropertySymbol property) => property.GetAttributes().Any(a => a.AttributeClass?.Name is "CsvExtensionDataAttribute" or "CsvExtensionData");

    private static List<IPropertySymbol> GetMappableProperties(INamedTypeSymbol typeSymbol)
    {
        var properties = new List<IPropertySymbol>();
        var currentType = typeSymbol;

        while (currentType != null && currentType.SpecialType != SpecialType.System_Object)
        {
            var members = currentType.GetMembers()
                .OfType<IPropertySymbol>()
                .Where(p => p.DeclaredAccessibility == Accessibility.Public && !p.IsStatic && p.SetMethod != null && !HasIgnoreAttribute(p) && !IsRowNumber(p) && !IsExtensionData(p));

            foreach (var member in members)
            {
                if (!properties.Any(p => p.Name == member.Name)) properties.Add(member);
            }
            currentType = currentType.BaseType;
        }
        return [.. properties.OrderBy(p => GetPropertyOrder(p))];
    }

