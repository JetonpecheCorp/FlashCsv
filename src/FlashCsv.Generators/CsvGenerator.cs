namespace FlashCsv.Generators;

[Generator]
public class CsvGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<TypeDeclarationSyntax> typeDeclarations = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (s, _) => IsSyntaxTargetForGeneration(s),
                transform: static (ctx, _) => GetSemanticTargetForGeneration(ctx))
            .Where(static m => m is not null)!;

        IncrementalValueProvider<(ImmutableArray<TypeDeclarationSyntax> Types, Compilation Compilation)> compilationAndTypes =
            typeDeclarations.Collect().Combine(context.CompilationProvider);

        context.RegisterSourceOutput(compilationAndTypes, static (spc, source) => Execute(source.Types, source.Compilation, spc));
    }

    private static bool IsSyntaxTargetForGeneration(SyntaxNode node)
    {
        return node is TypeDeclarationSyntax typeDecl && typeDecl.AttributeLists.Count > 0;
    }

    private static TypeDeclarationSyntax? GetSemanticTargetForGeneration(GeneratorSyntaxContext context)
    {
        var typeDecl = (TypeDeclarationSyntax)context.Node;
        foreach (var attributeListSyntax in typeDecl.AttributeLists)
        {
            foreach (var attributeSyntax in attributeListSyntax.Attributes)
            {
                string attrName = attributeSyntax.Name.ToString();
                if (attrName == "CsvSerializable" || attrName == "CsvSerializableAttribute")
                    return typeDecl;
            }
        }
        return null;
    }

    private static void Execute(ImmutableArray<TypeDeclarationSyntax> types, Compilation compilation, SourceProductionContext context)
    {
        if (types.IsDefaultOrEmpty) return;
        var distinctTypes = types.Distinct();

        foreach (var typeDecl in distinctTypes)
        {
            SemanticModel semanticModel = compilation.GetSemanticModel(typeDecl.SyntaxTree);
            if (semanticModel.GetDeclaredSymbol(typeDecl) is not INamedTypeSymbol typeSymbol) continue;

            string sourceCode = GenerateMapperCode(typeSymbol);
            string fileName = $"{typeSymbol.ContainingNamespace}.{typeSymbol.Name}_CsvMapper.g.cs"
                .Replace(".", "_").Replace("<", "_").Replace(">", "_");

            context.AddSource(fileName, Microsoft.CodeAnalysis.Text.SourceText.From(sourceCode, Encoding.UTF8));
        }
    }

    private static string GenerateMapperCode(INamedTypeSymbol typeSymbol)
    {
        string namespaceName = typeSymbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : $"namespace {typeSymbol.ContainingNamespace.ToDisplayString()};\n";
        string kind = typeSymbol.IsRecord ? (typeSymbol.IsValueType ? "record struct" : "record class") : (typeSymbol.IsValueType ? "struct" : "class");

        var discriminatorAttr = typeSymbol.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name is "CsvDiscriminatorAttribute" or "CsvDiscriminator");
        if (discriminatorAttr != null) return GeneratePolymorphicMapperCode(typeSymbol, discriminatorAttr);

        var properties = GetMappableProperties(typeSymbol);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS8600"); 
        sb.AppendLine("#pragma warning disable CS8601"); 
        sb.AppendLine("#pragma warning disable CS8602"); 
        sb.AppendLine("#pragma warning disable CS8604"); 
        sb.AppendLine("#pragma warning disable CS0162");
        sb.AppendLine("#pragma warning disable CS0108");
        sb.AppendLine("#pragma warning disable CS0219");

        sb.AppendLine("using System;");
        sb.AppendLine("using System.Text;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using FlashCsv.Core;");
        sb.AppendLine("using FlashCsv.Annotations;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine();
        sb.AppendLine(namespaceName);
        sb.AppendLine($"partial {kind} {typeSymbol.Name} : global::FlashCsv.Core.ICsvSerializable<{typeSymbol.Name}>");
        sb.AppendLine("{");
        sb.AppendLine($"    private static readonly {typeSymbol.Name} __defaultInstance = new {typeSymbol.Name}();");

        foreach (var prop in properties)
        {
            string? pattern = GetPattern(prop);
            if (!string.IsNullOrEmpty(pattern))
            {
                string escapedPattern = pattern!.Replace("\\", "\\\\").Replace("\"", "\\\"");
                sb.AppendLine($"    private static readonly global::System.Text.RegularExpressions.Regex __regex_{prop.Name} = new global::System.Text.RegularExpressions.Regex(\"{escapedPattern}\", global::System.Text.RegularExpressions.RegexOptions.Compiled);");
            }
        }
        sb.AppendLine();

        GenerateTryDeserialize(sb, typeSymbol, properties);
        sb.AppendLine();
        GenerateTrySerialize(sb, typeSymbol.Name, properties);
        sb.AppendLine();
        GenerateHeaderMapping(sb, typeSymbol.Name, properties);
        sb.AppendLine();
        GenerateHeaderNames(sb, properties);
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void GenerateHeaderNames(StringBuilder sb, List<IPropertySymbol> properties)
    {
        sb.AppendLine("    public static string[] GetHeaderNames()");
        sb.AppendLine("    {");
        sb.Append("        return [");
        var all = GetAllFlattenedProperties(properties);
        for (int i = 0; i < all.Count; i++)
        {
            var item = all[i];
            var (primaryName, _) = GetPropertyAliases(item.Property, item.Prefix);
            sb.Append($"\"{primaryName}\"");
            if (i < all.Count - 1) sb.Append(", ");
        }
        sb.AppendLine("];");
        sb.AppendLine("    }");
    }

    private static void GenerateHeaderMapping(StringBuilder sb, string typeName, List<IPropertySymbol> properties)
    {
        var all = GetAllFlattenedProperties(properties);
        sb.AppendLine("    public static int[] CreateColumnMap(ReadOnlySpan<string> headers, System.Collections.Generic.IReadOnlyDictionary<string, string>? dynamicMapping = null)");
        sb.AppendLine("    {");
        sb.AppendLine($"        int[] map = new int[{all.Count}];");
        sb.AppendLine("        Array.Fill(map, -1);");
        sb.AppendLine();

        for (int i = 0; i < all.Count; i++)
        {
            var item = all[i];
            string propName = item.Property.Name;
            string lookupKey = string.IsNullOrEmpty(item.Prefix) ? propName : $"{item.Prefix}{propName}";
            var (_, aliases) = GetPropertyAliases(item.Property, item.Prefix);

            sb.AppendLine($"        string[] aliases_{i} = new string[] {{ ");
            for (int a = 0; a < aliases.Count; a++)
            {
                sb.Append($"            \"{aliases[a]}\"");
                if (a < aliases.Count - 1) sb.Append(", ");
            }
            sb.AppendLine("        };");

            sb.AppendLine($"        map[{i}] = FindColumnIndex(headers, \"{lookupKey}\", [ {string.Join(", ", aliases.Select(a => $"\"{a}\""))} ], dynamicMapping);");
        }

        sb.AppendLine();
        sb.AppendLine("        return map;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static int FindColumnIndex(ReadOnlySpan<string> headers, string propKey, ReadOnlySpan<string> aliases, System.Collections.Generic.IReadOnlyDictionary<string, string>? dynamicMapping)");
        sb.AppendLine("    {");
        sb.AppendLine("        // 1. Priorité au mapping dynamique fourni à l'exécution");
        sb.AppendLine("        if (dynamicMapping != null)");
        sb.AppendLine("        {");
        sb.AppendLine("            string? dynamicHeader = null;");
        sb.AppendLine("            if (!dynamicMapping.TryGetValue(propKey, out dynamicHeader))");
        sb.AppendLine("            {");
        sb.AppendLine("                for (int a = 0; a < aliases.Length; a++)");
        sb.AppendLine("                {");
        sb.AppendLine("                    if (dynamicMapping.TryGetValue(aliases[a], out dynamicHeader)) break;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            if (!string.IsNullOrEmpty(dynamicHeader))");
        sb.AppendLine("            {");
        sb.AppendLine("                for (int i = 0; i < headers.Length; i++)");
        sb.AppendLine("                {");
        sb.AppendLine("                    if (string.Equals(headers[i], dynamicHeader, StringComparison.OrdinalIgnoreCase)) return i;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        // 2. Repli sur les alias compilés ([CsvName] et conventions de nommage)");
        sb.AppendLine("        for (int i = 0; i < headers.Length; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            for (int a = 0; a < aliases.Length; a++)");
        sb.AppendLine("            {");
        sb.AppendLine("                if (string.Equals(headers[i], aliases[a], StringComparison.OrdinalIgnoreCase)) return i;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        return -1;");
        sb.AppendLine("    }");
    }

    private static string GeneratePolymorphicMapperCode(INamedTypeSymbol typeSymbol, AttributeData discriminatorAttr)
    {
        string namespaceName = typeSymbol.ContainingNamespace.IsGlobalNamespace ? "" : $"namespace {typeSymbol.ContainingNamespace.ToDisplayString()};\n";
        string kind = typeSymbol.IsRecord ? (typeSymbol.IsValueType ? "record struct" : "record class") : (typeSymbol.IsValueType ? "struct" : "class");
        string typeName = typeSymbol.Name;
        string columnName = (string)discriminatorAttr.ConstructorArguments[0].Value!;

        var derivedTypes = typeSymbol.GetAttributes()
            .Where(a => a.AttributeClass?.Name is "CsvDerivedTypeAttribute" or "CsvDerivedType")
            .Select(a => (
                Type: (INamedTypeSymbol)a.ConstructorArguments[0].Value!,
                Value: (string)a.ConstructorArguments[1].Value!
            )).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#pragma warning disable CS0108");
        sb.AppendLine("#pragma warning disable CS0219");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using FlashCsv.Annotations;");
        sb.AppendLine("using FlashCsv.Core;");
        sb.AppendLine(namespaceName);
        sb.AppendLine($"partial {kind} {typeName} : ICsvSerializable<{typeName}>");
        sb.AppendLine("{");

        sb.AppendLine("    private static int _discriminatorIdx;");
        foreach (var derived in derivedTypes) 
            sb.AppendLine($"    private static int[] _map_{derived.Type.Name};");

        sb.AppendLine("    public static int[] CreateColumnMap(ReadOnlySpan<string> headers, System.Collections.Generic.IReadOnlyDictionary<string, string>? dynamicMapping = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        _discriminatorIdx = -1;");
        sb.AppendLine($"        string targetCol = (dynamicMapping != null && dynamicMapping.TryGetValue(\"{columnName}\", out var customCol) && !string.IsNullOrEmpty(customCol)) ? customCol : \"{columnName}\";");
        sb.AppendLine("        for(int i = 0; i < headers.Length; i++) if (string.Equals(headers[i], targetCol, StringComparison.OrdinalIgnoreCase)) _discriminatorIdx = i;");
        foreach (var derived in derivedTypes) 
            sb.AppendLine($"        _map_{derived.Type.Name} = {derived.Type.ToDisplayString()}.CreateColumnMap(headers, dynamicMapping);");
        sb.AppendLine("        return Array.Empty<int>();");
        sb.AppendLine("    }");

        sb.AppendLine($"    public static bool TryDeserialize(CsvRowView row, ReadOnlySpan<int> colMap, out {typeName} result, out CsvError error)");
        sb.AppendLine("    {");
        sb.AppendLine("        result = default!;");
        sb.AppendLine("        if (_discriminatorIdx == -1) { error = new CsvError(row.LineNumber, -1, null, CsvErrorCode.RequiredFieldMissing, ReadOnlyMemory<byte>.Empty); return false; }");
        sb.AppendLine("        var discriminatorSpan = row.GetRawField(_discriminatorIdx);");
        foreach (var derived in derivedTypes)
        {
            sb.AppendLine($"        if (discriminatorSpan.SequenceEqual(\"{derived.Value}\"u8))");
            sb.AppendLine("        {");
            sb.AppendLine($"            bool ok = {derived.Type.ToDisplayString()}.TryDeserialize(row, _map_{derived.Type.Name}, out var child, out error);");
            sb.AppendLine("            result = child; return ok;");
            sb.AppendLine("        }");
        }
        sb.AppendLine($"        error = new CsvError(row.LineNumber, _discriminatorIdx, \"{columnName}\", CsvErrorCode.InvalidValue, discriminatorSpan.ToArray());");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");
        
        sb.AppendLine("    public System.Threading.Tasks.ValueTask SerializeAsync(CsvStreamWriter writer, System.Threading.CancellationToken cancellationToken = default)");
        sb.AppendLine("    {");
        sb.AppendLine("        throw new NotImplementedException(\"Sérialisation polymorphe non implémentée sur la classe de base.\");");
        sb.AppendLine("    }");
        sb.AppendLine("    public static string[] GetHeaderNames() => Array.Empty<string>();");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static INamedTypeSymbol? GetIgnoreIfConditionType(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            var attrClass = attr.AttributeClass;
            if (attrClass == null) continue;
            if (attrClass.Name is "CsvIgnoreIfAttribute" or "CsvIgnoreIf" && attrClass.IsGenericType)
            {
                if (attrClass.TypeArguments.Length > 0 && attrClass.TypeArguments[0] is INamedTypeSymbol conditionType) return conditionType;
            }
        }
        return null;
    }

    private static INamedTypeSymbol? GetCustomConverter(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            var attrClass = attr.AttributeClass;
            if (attrClass == null) continue;
            string name = attrClass.Name;
            if (name is "CsvConverterAttribute" or "CsvConverter" && attrClass.IsGenericType)
            {
                if (attrClass.TypeArguments.Length > 0 && attrClass.TypeArguments[0] is INamedTypeSymbol genericArg) return genericArg;
            }
            if (name is "CsvConverterAttribute" or "CsvConverter")
            {
                if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is INamedTypeSymbol directType) return directType;
            }
        }
        return null;
    }

