                    case SpecialType.System_String:
                        sb.AppendLine($"                var span_{colIdent} = row.GetRawField(idx_{colIdent});");
                        sb.AppendLine($"                {targetVar} = row.GetString(span_{colIdent});");

                        sb.AppendLine($"                if (row.Options.TransformField != null)");
                        sb.AppendLine("                {");
                        sb.AppendLine($"                    {targetVar} = row.Options.TransformField(\"{colIdent}\", {targetVar});");
                        sb.AppendLine("                }");

                        var caseMode = GetCaseMode(prop);
                        if (caseMode.HasValue)
                        {
                            string caseEnum = caseMode.Value switch { 1 => "Lower", 2 => "Title", _ => "Upper" };
                            sb.AppendLine($"                {targetVar} = global::FlashCsv.Core.CsvSanitizer.ApplyCase({targetVar}, global::FlashCsv.Annotations.CsvCaseMode.{caseEnum});");
                        }

                        var sanitizeMode = GetHtmlSanitizeMode(prop);
                        if (sanitizeMode.HasValue)
                        {
                            string enumMember = sanitizeMode.Value == 1 ? "StripTags" : "Encode";
                            sb.AppendLine($"                {targetVar} = global::FlashCsv.Core.CsvSanitizer.Sanitize({targetVar}, global::FlashCsv.Annotations.HtmlSanitizeMode.{enumMember});");
                        }
                        else
                        {
                            sb.AppendLine($"                if (row.Options.DefaultHtmlSanitizeMode.HasValue)");
                            sb.AppendLine("                {");
                            sb.AppendLine($"                    {targetVar} = global::FlashCsv.Core.CsvSanitizer.Sanitize({targetVar}, row.Options.DefaultHtmlSanitizeMode.Value);");
                            sb.AppendLine("                }");
                        }

                        AppendLengthBoundsValidation(sb, colIdent, targetVar, prop);

                        string? pattern = GetPattern(prop);
                        if (!string.IsNullOrEmpty(pattern))
                        {
                            sb.AppendLine($"                if (!__regex_{prop.Name}.IsMatch({targetVar}))");
                            sb.AppendLine("                {");
                            sb.AppendLine($"                    error = new CsvError(row.LineNumber, idx_{colIdent}, \"{colIdent}\", CsvErrorCode.PatternMismatch, row.GetRawField(idx_{colIdent}).ToArray());");
                            sb.AppendLine("                    return false;");
                            sb.AppendLine("                }");
                        }

                        var allowedValues = GetAllowedValues(prop);
                        if (allowedValues?.Length > 0)
                        {
                            string checkCondition = string.Join(" && ", allowedValues.Select(v => $"!string.Equals({targetVar}, \"{v}\", StringComparison.OrdinalIgnoreCase)"));
                            sb.AppendLine($"                if ({checkCondition})");
                            sb.AppendLine("                {");
                            sb.AppendLine($"                    error = new CsvError(row.LineNumber, idx_{colIdent}, \"{colIdent}\", CsvErrorCode.InvalidValue, row.GetRawField(idx_{colIdent}).ToArray());");
                            sb.AppendLine("                    return false;");
                            sb.AppendLine("                }");
                        }
                        break;

                    case SpecialType.System_DateTime:
                        string? customFormat = GetCustomFormat(prop);
                        string dtFormatArg = customFormat != null ? $"\"{customFormat}\"" : "null";
                        sb.Append(declareTemp);
                        sb.AppendLine($"                if (!row.TryGetDateTime(idx_{colIdent}, \"{colIdent}\", {dtFormatArg}, out {innerTarget}, out error)) return false;");
                        if (isNullableStruct) sb.AppendLine($"                {targetVar} = {innerTarget};");
                        break;

                    default:
                        string typeFullName = effectiveType.ToDisplayString();
                        string? customFormat2 = GetCustomFormat(prop);
                        string formatArg2 = customFormat2 != null ? $"\"{customFormat2}\"" : "null";

                        if (typeFullName == "System.DateOnly")
                        {
                            sb.Append(declareTemp);
                            sb.AppendLine($"                if (!row.TryGetDateOnly(idx_{colIdent}, \"{colIdent}\", {formatArg2}, out {innerTarget}, out error)) return false;");
                            if (isNullableStruct) sb.AppendLine($"                {targetVar} = {innerTarget};");
                        }
                        else if (typeFullName == "System.TimeOnly")
                        {
                            sb.Append(declareTemp);
                            sb.AppendLine($"                if (!row.TryGetTimeOnly(idx_{colIdent}, \"{colIdent}\", {formatArg2}, out {innerTarget}, out error)) return false;");
                            if (isNullableStruct) sb.AppendLine($"                {targetVar} = {innerTarget};");
                        }
                        else if (typeFullName == "System.Guid")
                        {
                            sb.Append(declareTemp);
                            sb.AppendLine($"                if (!row.TryGetGuid(idx_{colIdent}, \"{colIdent}\", out {innerTarget}, out error)) return false;");
                            if (isNullableStruct) sb.AppendLine($"                {targetVar} = {innerTarget};");
                        }
                        else if (GetDelimiterArrayInfo(prop) is var arrayInfo && arrayInfo.HasValue && IsArrayOrList(effectiveType, out var elemType, out bool isGenericList))
                        {
                            char splitChar = arrayInfo.Value.Delimiter;
                            char escChar = arrayInfo.Value.EscapeChar;
                            string escCharLiteral = escChar == '\0' ? "'\\0'" : (escChar == '\\' ? "'\\\\'" : $"'{escChar}'");
                            string splitCharLiteral = splitChar == '\\' ? "'\\\\'" : $"'{splitChar}'";

                            string elemTypeName = elemType.ToDisplayString();
                            sb.AppendLine($"                var rawSpan_{colIdent} = row.GetRawField(idx_{colIdent});");
                            sb.AppendLine($"                string rawStr_{colIdent} = rawSpan_{colIdent}.IsEmpty ? string.Empty : Encoding.UTF8.GetString(rawSpan_{colIdent});");
                            sb.AppendLine($"                var parts_{colIdent} = global::FlashCsv.Core.CsvSanitizer.SplitWithEscape(rawStr_{colIdent}, {splitCharLiteral}, {escCharLiteral});");

                            if (elemType.SpecialType == SpecialType.System_String)
                            {
                                if (isGenericList)
                                    sb.AppendLine($"                {targetVar} = new global::System.Collections.Generic.List<string>(parts_{colIdent});");
                                else
                                    sb.AppendLine($"                {targetVar} = parts_{colIdent};");
                            }
                            else if (elemType.SpecialType == SpecialType.System_Int32)
                            {
                                sb.AppendLine($"                var parsedArr_{colIdent} = new int[parts_{colIdent}.Length];");
                                sb.AppendLine($"                for (int p = 0; p < parts_{colIdent}.Length; p++)");
                                sb.AppendLine("                {");
                                sb.AppendLine($"                    if (!int.TryParse(parts_{colIdent}[p], out parsedArr_{colIdent}[p]))");
                                sb.AppendLine("                    {");
                                sb.AppendLine($"                        error = new CsvError(row.LineNumber, idx_{colIdent}, \"{colIdent}\", CsvErrorCode.InvalidInteger, rawSpan_{colIdent}.ToArray());");
                                sb.AppendLine("                        return false;");
                                sb.AppendLine("                    }");
                                sb.AppendLine("                }");
                                if (isGenericList)
                                    sb.AppendLine($"                {targetVar} = new global::System.Collections.Generic.List<int>(parsedArr_{colIdent});");
                                else
                                    sb.AppendLine($"                {targetVar} = parsedArr_{colIdent};");
                            }
                            else
                            {
                                sb.AppendLine($"                #error Type d'élément '{elemTypeName}' non supporté pour [CsvDelimiterArray].");
                            }
                        }
                        else
                        {
                            sb.AppendLine($"                #error Type '{prop.Type.ToDisplayString()}' non pris en charge pour la propriété '{colIdent}'.");
                        }
                        break;
                }
            }

            // FERMETURE DU BLOC ELSE DE LA SÉCURITÉ DE NULLITÉ
            if (needsNullCheck)
            {
                sb.AppendLine("            }");
            }

            // FERMETURE DU BLOC IF PRINCIPAL
            sb.AppendLine("        }");

            // BLOC FALLBACK ROBUSTE POUR COLONNE ABSENTE DU CSV (index -1)
            sb.AppendLine("        else");
            sb.AppendLine("        {");

            if (isBoolWithFallback)
            {
                bool fallbackVal = boolCustom!.Value.TrueValues.Length == 0;
                sb.AppendLine($"            {targetVar} = {(fallbackVal ? "true" : "false")};");
            }
            else
            {
                sb.AppendLine($"            if (isRequired_{colIdent})");
                sb.AppendLine("            {");
                sb.AppendLine($"                error = new CsvError(row.LineNumber, idx_{colIdent}, \"{colIdent}\", CsvErrorCode.RequiredFieldMissing, ReadOnlyMemory<byte>.Empty);");
                sb.AppendLine("                return false;");
                sb.AppendLine("            }");
                if (!hasDefault)
                {
                    sb.AppendLine($"            else");
                    sb.AppendLine("            {");
                    sb.AppendLine($"                {targetVar} = default!;");
                    sb.AppendLine("            }");
                }
            }

            sb.AppendLine("        }");

            if (ignoreIfConditionType != null && item.ParentProp == null)
            {
                sb.AppendLine("        }"); // Fin de if (IgnoreIfCondition)
            }
            sb.AppendLine();
        }

        var extensionDataProp = typeSymbol.GetMembers().OfType<IPropertySymbol>().FirstOrDefault(IsExtensionData);
        if (extensionDataProp != null)
        {
            sb.AppendLine("        var __extData = new global::System.Collections.Generic.Dictionary<string, string>();");
            sb.AppendLine("        for (int c = 0; c < row.FieldCount; c++)");
            sb.AppendLine("        {");
            sb.AppendLine("            bool isMapped = false;");
            sb.AppendLine("            foreach (int mappedIdx in colMap)");
            sb.AppendLine("            {");
            sb.AppendLine("                if (mappedIdx == c) { isMapped = true; break; }");
            sb.AppendLine("            }");
            sb.AppendLine("            if (!isMapped)");
            sb.AppendLine("            {");
            sb.AppendLine("                var spanExt = row.GetRawField(c);");
            sb.AppendLine("                string valExt = spanExt.IsEmpty ? string.Empty : Encoding.UTF8.GetString(spanExt);");
            sb.AppendLine("                string headerName = row.Headers != null && c < row.Headers.Length ? row.Headers[c] : $\"Column_{c}\";");
            sb.AppendLine("                __extData[headerName] = valExt;");
            sb.AppendLine("            }");
            sb.AppendLine("        }");
        }

        sb.AppendLine($"        result = new {typeName}");
        sb.AppendLine("        {");

        var rowNumberProp = typeSymbol.GetMembers().OfType<IPropertySymbol>().FirstOrDefault(IsRowNumber);
        if (rowNumberProp != null)
        {
            string cast = rowNumberProp.Type.SpecialType == SpecialType.System_Int32 ? "(int)" : "(long)";
            sb.AppendLine($"            {rowNumberProp.Name} = {cast}row.LineNumber,");
        }

        if (extensionDataProp != null)
        {
            sb.AppendLine($"            {extensionDataProp.Name} = __extData,");
        }

        foreach (var prop in properties)
        {
            var (isFlattened, _) = GetFlattenInfo(prop);
            if (isFlattened && prop.Type is INamedTypeSymbol childType)
            {
                var childProps = GetMappableProperties(childType);
                sb.AppendLine($"            {prop.Name} = new {childType.ToDisplayString()}");
                sb.AppendLine("            {");
                foreach (var child in childProps)
                {
                    sb.AppendLine($"                {child.Name} = __hasValue_{prop.Name}_{child.Name} ? __{prop.Name}_{child.Name} : __defaultInstance.{prop.Name}.{child.Name},");
                }
                sb.AppendLine("            },");
            }
            else
            {
                sb.AppendLine($"                {prop.Name} = __{prop.Name},");
            }
        }
        sb.AppendLine("        };");
        sb.AppendLine();
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");
    }

    private static ITypeSymbol UnwrapNullable(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol named && 
            named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T && 
            named.TypeArguments.Length > 0)
        {
            return named.TypeArguments[0];
        }
        return type;
    }

    private static string FormatNumericLiteral(object val, SpecialType specialType)
    {
        return specialType switch
        {
            SpecialType.System_Decimal => $"{Convert.ToString(Convert.ToDecimal(val), System.Globalization.CultureInfo.InvariantCulture)}m",
            SpecialType.System_Single => $"{Convert.ToString(Convert.ToSingle(val), System.Globalization.CultureInfo.InvariantCulture)}f",
            SpecialType.System_Double => $"{Convert.ToString(Convert.ToDouble(val), System.Globalization.CultureInfo.InvariantCulture)}d",
            SpecialType.System_Int64 => $"{Convert.ToInt64(val)}L",
            _ => $"{Convert.ToInt32(val)}"
        };
    }

    private static void AppendNumericBoundsValidation(StringBuilder sb, string propName, string targetVar, IPropertySymbol prop, SpecialType specialType)
    {
        var (min, max) = GetNumericBounds(prop);
        if (min == null && max == null) return;

        var conditions = new List<string>();

        if (min != null)
        {
            string minStr = FormatNumericLiteral(min, specialType);
            conditions.Add($"{targetVar} < {minStr}");
        }

        if (max != null)
        {
            string maxStr = FormatNumericLiteral(max, specialType);
            conditions.Add($"{targetVar} > {maxStr}");
        }

        string fullCondition = string.Join(" || ", conditions);

        sb.AppendLine($"                if ({fullCondition})");
        sb.AppendLine("                {");
        sb.AppendLine($"                    error = new CsvError(row.LineNumber, idx_{propName}, \"{propName}\", CsvErrorCode.ValueOutOfRange, row.GetRawField(idx_{propName}).ToArray());");
        sb.AppendLine("                    return false;");
        sb.AppendLine("                }");
    }

    private static void AppendLengthBoundsValidation(StringBuilder sb, string propName, string targetVar, IPropertySymbol prop)
    {
        var (min, max) = GetLengthBounds(prop);
        if (min == null && max == null) return;

        var conditions = new List<string>();

        if (min != null)
        {
            conditions.Add($"{targetVar}.Length < {min.Value}");
        }

        if (max != null)
        {
            conditions.Add($"{targetVar}.Length > {max.Value}");
        }

        string fullCondition = string.Join(" || ", conditions);

        sb.AppendLine($"                if ({fullCondition})");
        sb.AppendLine("                {");
        sb.AppendLine($"                    error = new CsvError(row.LineNumber, idx_{propName}, \"{propName}\", CsvErrorCode.InvalidLength, row.GetRawField(idx_{propName}).ToArray());");
        sb.AppendLine("                    return false;");
        sb.AppendLine("                }");
    }

    private static string ToSnakeCase(string text)
    {
        if (string.IsNullOrEmpty(text)) return text;
        var sb = new StringBuilder();
        for (int i = 0; i < text.Length; i++)
        {
            char c = text[i];
            if (char.IsUpper(c))
            {
                if (i > 0) sb.Append('_');
                sb.Append(char.ToLowerInvariant(c));
            }
            else
            {
                sb.Append(c);
            }
        }
        return sb.ToString();
    }

    private static string ToKebabCase(string text)
    {
        if (string.IsNullOrEmpty(text)) return text;
        var sb = new StringBuilder();
        for (int i = 0; i < text.Length; i++)
        {
            char c = text[i];
            if (char.IsUpper(c))
            {
                if (i > 0) sb.Append('-');
                sb.Append(char.ToLowerInvariant(c));
            }
            else
            {
                sb.Append(c);
            }
        }
        return sb.ToString();
    }

    private static string ToCamelCase(string text)
    {
        if (string.IsNullOrEmpty(text) || char.IsLower(text[0])) return text;
        return char.ToLowerInvariant(text[0]) + text.Substring(1);
    }
