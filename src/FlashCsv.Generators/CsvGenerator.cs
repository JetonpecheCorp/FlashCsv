    private static (string PrimaryName, List<string> AllAliases) GetEnumMemberDetails(IFieldSymbol enumField)
    {
        string primaryName = enumField.Name;
        var allAliases = new List<string> { enumField.Name };

        foreach (var attr in enumField.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvEnumMemberNameAttribute" or "CsvEnumMemberName" && attr.ConstructorArguments.Length > 0)
            {
                if (attr.ConstructorArguments[0].Value is string customName && !string.IsNullOrEmpty(customName))
                {
                    primaryName = customName;
                    allAliases.Add(customName);
                }
                if (attr.ConstructorArguments.Length > 1)
                {
                    var aliasArg = attr.ConstructorArguments[1];
                    if (aliasArg.Values.Length > 0)
                    {
                        foreach (var val in aliasArg.Values)
                        {
                            if (val.Value is string alias && !string.IsNullOrEmpty(alias)) allAliases.Add(alias);
                        }
                    }
                }
            }
        }
        return (primaryName, allAliases.Distinct().ToList());
    }

