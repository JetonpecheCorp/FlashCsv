    private static string[]? GetCustomNullValues(IPropertySymbol property)
    {
        foreach (var attr in property.GetAttributes())
        {
            if (attr.AttributeClass?.Name is "CsvNullValuesAttribute" or "CsvNullValues")
            {
                if (attr.ConstructorArguments.Length > 0)
                {
                    var arg = attr.ConstructorArguments[0];
                    if (arg.Values.Length > 0)
                    {
                        return [.. arg.Values.Select(v => v.Value?.ToString() ?? "").Where(s => !string.IsNullOrEmpty(s))];
